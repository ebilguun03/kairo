#!/usr/bin/env python3
"""
seed-menu-sales.py
------------------
Optional importer for locally supplied, authorized Toast-compatible ProductMix xlsx exports.
No real exports are distributed with this repository. For the bundled synthetic demo,
use node scripts/generate-demo-sales.mjs.

Parses three ProductMix xlsx exports and prints SQL INSERT
statements for the menu_sales table. Pipe the output into psql or
paste into the Supabase SQL editor.

Usage:
  python3 scripts/seed-menu-sales.py > /tmp/menu_sales_seed.sql

Requires: openpyxl  (pip install openpyxl)

The script resolves the fictional demo tenant's restaurant_id from the restaurants table
via a sub-select so it works across any Supabase project.
"""

import sys
import os
import openpyxl

# ---------------------------------------------------------------------------
# File map: (month label, path to xlsx)
# Adjust paths if you move the exports.
# ---------------------------------------------------------------------------
EXPORTS = [
    ("2026-01", "ProductMix_2026-01-01_2026-01-31.xlsx"),
    ("2026-02", "ProductMix_2026-02-01_2026-02-28.xlsx"),
    ("2026-03", "ProductMix_2026-03-01_2026-03-31.xlsx"),
]

# Look for the files relative to this script, or in a sibling data/ directory
SEARCH_DIRS = [
    os.path.join(os.path.dirname(__file__), "..", "data"),
    os.path.join(os.path.dirname(__file__)),
]

# Menu group lookup — built from the "All levels" sheet which has
# (menu_group, item_name) pairs. We'll populate this per file.
def build_group_map(wb):
    """Return {item_name: menu_group} from the 'All levels' sheet."""
    ws = wb["All levels"]
    group_map = {}
    current_group = None
    for row in ws.iter_rows(min_row=2, values_only=True):
        # Columns: Type, Menu, Menu group, Subgroup, Item, ...
        row_type = row[0]
        menu_group = row[2]
        item_name = row[4]
        if menu_group:
            current_group = menu_group
        if row_type == "menuItem" and item_name and current_group:
            group_map[item_name.strip()] = current_group
    return group_map


def find_file(filename):
    for d in SEARCH_DIRS:
        p = os.path.join(d, filename)
        if os.path.exists(p):
            return p
    return None


def escape(s):
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"


def main():
    rows = []

    for month, filename in EXPORTS:
        path = find_file(filename)
        if not path:
            print(f"-- WARNING: could not find {filename}, skipping", file=sys.stderr)
            continue

        wb = openpyxl.load_workbook(path)
        group_map = build_group_map(wb)

        ws = wb["Items"]
        headers = None
        for i, row in enumerate(ws.iter_rows(values_only=True)):
            if i == 0:
                headers = [str(h).strip() if h else "" for h in row]
                continue
            if i == 1:
                # Total row — skip
                continue

            item_name = row[0]
            if not item_name:
                continue

            item_name = item_name.strip()
            qty       = int(row[2])  if row[2] is not None else 0
            avg_price = float(row[3]) if row[3] is not None else None
            gross     = float(row[5]) if row[5] is not None else 0
            discount  = float(row[6]) if row[6] is not None else 0
            net       = float(row[9]) if row[9] is not None else 0
            menu_group = group_map.get(item_name)

            rows.append((month, item_name, menu_group, qty, gross, net, avg_price, discount))

    if not rows:
        print("-- No data found. Check that xlsx files are in data/ or scripts/", file=sys.stderr)
        sys.exit(1)

    print("-- menu_sales seed — generated by scripts/seed-menu-sales.py")
    print("-- Restaurant is resolved by slug 'paper-lantern-demo' at insert time.")
    print()
    print("DO $$")
    print("DECLARE rid uuid;")
    print("BEGIN")
    print("  SELECT id INTO rid FROM restaurants WHERE slug = 'paper-lantern-demo';")
    print("  IF rid IS NULL THEN")
    print("    RAISE EXCEPTION 'No restaurant with slug paper-lantern-demo found. Run the initial seed first.';")
    print("  END IF;")
    print()

    for (month, item, group, qty, gross, net, avg_price, discount) in rows:
        avg_str = f"{avg_price:.2f}" if avg_price is not None else "NULL"
        print(
            f"  INSERT INTO menu_sales "
            f"(restaurant_id, month, item, menu_group, qty_sold, gross_sales, net_sales, avg_price, discount_amt) "
            f"VALUES ("
            f"rid, {escape(month)}, {escape(item)}, {escape(group)}, "
            f"{qty}, {gross:.2f}, {net:.2f}, {avg_str}, {discount:.2f}"
            f") ON CONFLICT (restaurant_id, month, item) DO UPDATE SET "
            f"qty_sold=EXCLUDED.qty_sold, gross_sales=EXCLUDED.gross_sales, "
            f"net_sales=EXCLUDED.net_sales, avg_price=EXCLUDED.avg_price, "
            f"discount_amt=EXCLUDED.discount_amt;"
        )

    print()
    print("END $$;")
    print()
    print(f"-- Done: {len(rows)} rows across {len(EXPORTS)} months.")


if __name__ == "__main__":
    main()
